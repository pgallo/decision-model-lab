"""Shared helpers for the domain experiments."""

from __future__ import annotations

from dataclasses import dataclass, field


@dataclass
class Report:
    domain: str
    title: str
    summary: list[str] = field(default_factory=list)  # short lines for the console
    sections: list[str] = field(default_factory=list)  # Markdown blocks for the report file
    metrics: dict[str, float] = field(default_factory=dict)  # for tests and CI checks

    def add(self, heading: str, body: str) -> None:
        self.sections.append(f"## {heading}\n\n{body.strip()}\n")

    def to_markdown(self, seed: int) -> str:
        head = [
            f"# {self.title}",
            "",
            f"Synthetic data, seed {seed}. Generated by `decision-lab run {self.domain}`.",
            "",
            "## Summary",
            "",
            *[f"- {line}" for line in self.summary],
            "",
        ]
        return "\n".join(head) + "\n" + "\n".join(self.sections)

    def to_console(self) -> str:
        return "\n".join([self.title, "=" * len(self.title), *[f"  {s}" for s in self.summary]])
